defmodule Mix.Tasks.Graphvix.Gen.Attributes do
  @shortdoc "Regenerates Graphvix.Attributes from the Graphviz attribute reference"

  @moduledoc """
  Regenerates `lib/graphvix/attributes.ex` from the Graphviz attribute
  reference at https://graphviz.org/doc/info/attrs.html.

      mix graphvix.gen.attributes
      mix graphvix.gen.attributes --from path/to/attrs.html

  `--from` reads a saved copy of the page instead of fetching it. The
  generated module is checked in; review its diff like any other change.
  Builds never run this task.
  """

  use Mix.Task

  @url "https://graphviz.org/doc/info/attrs.html"
  @target "lib/graphvix/attributes.ex"
  @letters %{"Graphs" => :G, "Subgraphs" => :S, "Clusters" => :C, "Nodes" => :N, "Edges" => :E}
  @order [:G, :S, :C, :N, :E]

  @impl Mix.Task
  def run(args) do
    {opts, _rest} = OptionParser.parse!(args, strict: [from: :string])
    html = read(opts[:from])
    rows = parse(html)

    if rows == [], do: Mix.raise("no attribute rows found; has the page layout changed?")

    File.write!(@target, render(rows, page_modified(html)))
    Mix.Task.run("format", [@target])
    Mix.shell().info("Wrote #{length(rows)} attributes to #{@target}")
  end

  @doc """
  Parses the reference page's attribute table into `{name, letters}` rows, in
  page order, with letters ordered `:G, :S, :C, :N, :E`.
  """
  @spec parse(String.t()) :: [{String.t(), [:G | :S | :C | :N | :E]}]
  def parse(html) do
    ~r/<TD><A ID="a:([^"]+)"[^\n]*\n\s*<TD>([^<]*)<\/TD>/
    |> Regex.scan(html, capture: :all_but_first)
    |> Enum.map(fn [name, used_by] -> {name, letters(used_by)} end)
  end

  defp letters(used_by) do
    found =
      used_by
      |> String.split(",", trim: true)
      |> Enum.map(&Map.fetch!(@letters, String.trim(&1)))

    Enum.filter(@order, &(&1 in found))
  end

  defp read(nil) do
    case Mix.Utils.read_path(@url) do
      {:ok, html} -> html
      other -> Mix.raise("could not fetch #{@url}: #{inspect(other)}")
    end
  end

  defp read(path), do: File.read!(path)

  defp page_modified(html) do
    case Regex.run(~r/itemprop="dateModified" content="(\d{4}-\d{2}-\d{2})/, html) do
      [_, date] -> date
      nil -> "unknown"
    end
  end

  defp render(rows, page_modified) do
    entries =
      Enum.map_join(rows, ",\n", fn {name, letters} ->
        "    {#{inspect(name)}, #{inspect(letters)}}"
      end)

    """
    defmodule Graphvix.Attributes do
      @moduledoc \"\"\"
      The Graphviz attribute table: which kinds of element use each attribute.

      Generated by `mix graphvix.gen.attributes`; do not edit by hand. Letters
      are `:G` (graphs), `:S` (subgraphs), `:C` (clusters), `:N` (nodes) and
      `:E` (edges).
      \"\"\"

      @source %{
        url: #{inspect(@url)},
        page_modified: #{inspect(page_modified)},
        generated_on: #{inspect(Date.to_iso8601(Date.utc_today()))}
      }

      @attributes [
    #{entries}
      ]

      @lookup Map.new(@attributes)

      @doc "The letters for an attribute name, or `:error` for an unknown name."
      @spec lookup(String.t()) :: {:ok, [:G | :S | :C | :N | :E]} | :error
      def lookup(name) when is_binary(name), do: Map.fetch(@lookup, name)
      def lookup(_name), do: :error

      @doc "Every known attribute name, in the reference's order."
      @spec names() :: [String.t()]
      def names, do: Enum.map(@attributes, &elem(&1, 0))

      @doc "Where and when the table was generated."
      @spec source() :: %{url: String.t(), page_modified: String.t(), generated_on: String.t()}
      def source, do: @source
    end
    """
  end
end
