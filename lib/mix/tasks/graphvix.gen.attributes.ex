defmodule Mix.Tasks.Graphvix.Gen.Attributes do
  @moduledoc """
  Generate list of attributes and their valid targets from Graphviz documentation.
  """

  use Mix.Task

  @url "https://graphviz.org/doc/info/attrs.html"

  @shortdoc "hello"
  def run(_) do
    case Mix.Utils.read_path(@url) do
      {:ok, html} ->
        attributes = html |> parse()

        modified =
          case Regex.run(~r/itemprop="dateModified".*content="(\d{4}-\d{2}-\d{2})/, html) do
            [_, date] -> date
            _ -> "unknown"
          end

        File.write!("lib/graphvix/attributes.ex", output(attributes, modified))

      _ ->
        :error
    end
  end

  @elements %{
    "Graphs" => :G,
    "Subgraphs" => :S,
    "Clusters" => :C,
    "Nodes" => :N,
    "Edges" => :E
  }
  @elements_order ~w(G S C N E)a

  def parse(html) do
    ~r/<TD><A ID="a:([^"]+)"[^\n]*\n\s*<TD>([^<]+)/
    |> Regex.scan(html, capture: :all_but_first)
    |> Enum.map(fn [label, elements] ->
      elements =
        String.split(elements, ~r/,\s*/, trim: true)
        |> Enum.map(&@elements[&1])
        |> Enum.sort_by(&Enum.find_index(@elements_order, fn l -> l == &1 end))

      {label, elements}
    end)
  end

  defp output(attributes, modified_at) do
    attrs =
      Enum.map_join(attributes, ",\n", fn {k, v} ->
        "    #{inspect(k)} => #{inspect(v)}"
      end)

    """
    # Generated by `mix graphvix.gen.attributes`; DO NOT EDIT BY HAND.
    defmodule Graphvix.Attributes do
      @attributes %{
    #{attrs}
      }

      def source do
        %{
          url: #{inspect(@url)},
          page_modified: #{inspect(modified_at)}, 
          generated_on: #{inspect(Date.to_string(Date.utc_today()))}
        }
      end

      def names, do: Map.keys(@attributes)

      @spec lookup(String.t()) :: :error | {:ok, nonempty_list()}
      def lookup(name), do: Map.fetch(@attributes, name)
    end
    """
  end
end
